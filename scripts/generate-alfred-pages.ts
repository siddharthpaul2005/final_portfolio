/**
 * Generates api/_lib/pages.generated.ts: the readable text and headings of every MDX page
 * (project write-ups and blog posts), so ALFRED's read_page tool can answer detailed questions
 * about them. Runs before `vite build` and when the dev server starts; commit the output so the
 * Vercel function always has it.
 */
import fs from 'fs';
import path from 'path';

const ROOT = process.cwd();
const OUT = path.join(ROOT, 'api', '_lib', 'pages.generated.ts');
const MAX_CHARS = 3500; // keeps one read_page result well inside the model's rate limits

type PageText = { headings: string[]; text: string };

const toText = (mdx: string): PageText => {
  const body = mdx
    .replace(/\r\n/g, '\n')
    .replace(/^import .+ from .+;?$/gm, '') // MDX imports
    .replace(/^export .+$/gm, '')
    .replace(/```[\s\S]*?```/g, '[code sample]')
    .replace(/<[A-Z][\s\S]*?\/>/g, '') // embedded components
    .replace(/<\/?[a-zA-Z][^>]*>/g, '')
    .replace(/!\[[^\]]*\]\([^)]*\)/g, '') // images
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1') // links keep their text
    .replace(/[*_`]/g, '')
    .replace(/\n{3,}/g, '\n\n')
    .trim();
  const headings = [...body.matchAll(/^#{2,3}\s+(.+)$/gm)].map((m) => m[1].trim());
  return { headings, text: body.length > MAX_CHARS ? `${body.slice(0, MAX_CHARS)}…` : body };
};

const collect = (dir: string, route: string) => {
  const abs = path.join(ROOT, 'src', 'content', dir);
  if (!fs.existsSync(abs)) return {};
  return Object.fromEntries(
    fs
      .readdirSync(abs)
      .filter((f) => f.endsWith('.mdx'))
      .sort()
      .map((f) => [`${route}/${f.replace(/\.mdx$/, '')}`, toText(fs.readFileSync(path.join(abs, f), 'utf-8'))]),
  );
};

export const generateAlfredPages = () => {
  const pages: Record<string, PageText> = { ...collect('projects', '/projects'), ...collect('blog', '/blog') };
  const source = `// Generated by scripts/generate-alfred-pages.ts. Do not edit by hand.\n\nexport const pageTexts: Record<string, { headings: string[]; text: string }> = ${JSON.stringify(pages, null, 2)};\n`;
  // Only write on change, so the dev server doesn't reload for nothing.
  if (!fs.existsSync(OUT) || fs.readFileSync(OUT, 'utf-8') !== source) fs.writeFileSync(OUT, source);
  return Object.keys(pages).length;
};

if (process.argv[1]?.replace(/\\/g, '/').endsWith('scripts/generate-alfred-pages.ts')) {
  console.log(`✅ ALFRED page index: ${generateAlfredPages()} pages`);
}
